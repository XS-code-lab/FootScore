"""CI-only migration-owner versus real runtime LOGIN role separation.

All mutations occur in the disposable restored PostgreSQL CI database
(except CREATE/DROP ROLE, which are cluster-global but restricted to CI).
The temporary user has a random, test-only password, never printed.
"""
import os
import secrets

from sqlalchemy.engine import make_url


RUNTIME_ROLE = "footscore_ci_app_runtime"
FUTURE_TABLE = "public.ci_future_runtime_grants"


def require_disposable_ci() -> None:
    url = make_url(os.environ.get("DATABASE_URL", "sqlite:///"))
    if (
        os.environ.get("GITHUB_ACTIONS") != "true"
        or os.environ.get("FOOTSCORE_INTEGRATION_TESTS") != "1"
        or os.environ.get("PGHOST") != "127.0.0.1"
        or os.environ.get("PGDATABASE") != "footscore"
        or os.environ.get("PGUSER") != "footscore"
        or url.drivername != "postgresql+psycopg"
        or url.host != "127.0.0.1"
        or url.username != "footscore"
        or url.database != "footscore_restore_ci"
    ):
        raise RuntimeError("Role separation smoke requires disposable restore CI only")


def _assert_denied(cursor, statement: str) -> None:
    import psycopg

    cursor.execute("SAVEPOINT ci_runtime_permission_gate")
    try:
        cursor.execute(statement)
    except psycopg.errors.InsufficientPrivilege:
        cursor.execute("ROLLBACK TO SAVEPOINT ci_runtime_permission_gate")
    else:
        cursor.execute("ROLLBACK TO SAVEPOINT ci_runtime_permission_gate")
        raise AssertionError("A non-owner runtime was allowed to change schema")


def run() -> None:
    require_disposable_ci()  # Must run before any database connection.
    import psycopg
    from psycopg import sql

    from app.db_role_audit import audit_runtime_connection

    password = secrets.token_urlsafe(48)
    admin_params = {
        "host": "127.0.0.1", "port": os.environ.get("PGPORT", "5432"),
        "dbname": "footscore_restore_ci", "user": "footscore",
        "connect_timeout": 5, "autocommit": True,
    }
    role = sql.Identifier(RUNTIME_ROLE)
    with psycopg.connect(**admin_params) as admin:
        with admin.cursor() as owner:
            admin_report = audit_runtime_connection(admin, "footscore")
            assert not admin_report["runtime_role_policy_passed"]
            assert admin_report["is_superuser"]
            owner.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (RUNTIME_ROLE,))
            if owner.fetchone() is not None:
                raise RuntimeError("CI runtime role already exists")
            owner.execute(
                sql.SQL("CREATE ROLE {} LOGIN PASSWORD {} "
                        "NOSUPERUSER NOCREATEDB NOCREATEROLE "
                        "NOREPLICATION NOBYPASSRLS NOINHERIT").format(
                    role, sql.Literal(password),
                )
            )
            try:
                owner.execute(
                    sql.SQL("GRANT CONNECT ON DATABASE footscore_restore_ci TO {}").format(
                        role,
                    )
                )
                owner.execute(
                    sql.SQL("GRANT USAGE ON SCHEMA public TO {}").format(role)
                )
                owner.execute(
                    sql.SQL(
                        "GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES "
                        "IN SCHEMA public TO {}"
                    ).format(role)
                )
                owner.execute(
                    sql.SQL(
                        "GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO {}"
                    ).format(role)
                )
                # Only future objects created by THIS migration owner
                # in THIS database will receive these grants.
                owner.execute(
                    sql.SQL(
                        "ALTER DEFAULT PRIVILEGES FOR ROLE footscore IN SCHEMA public "
                        "GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO {}"
                    ).format(role)
                )
                owner.execute(
                    sql.SQL(
                        "ALTER DEFAULT PRIVILEGES FOR ROLE footscore IN SCHEMA public "
                        "GRANT USAGE, SELECT ON SEQUENCES TO {}"
                    ).format(role)
                )
                owner.execute(
                    "SELECT rolsuper, rolcreatedb, rolcreaterole, rolreplication, "
                    "rolbypassrls, rolcanlogin FROM pg_roles WHERE rolname = %s",
                    (RUNTIME_ROLE,),
                )
                assert owner.fetchone() == (False, False, False, False, False, True)
                owner.execute(
                    "SELECT pg_has_role('footscore_ci_app_runtime', 'footscore', 'MEMBER')"
                )
                assert owner.fetchone()[0] is False

                owner.execute(
                    f"CREATE TABLE {FUTURE_TABLE} ("
                    "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    "note TEXT NOT NULL)"
                )
                runtime_params = {
                    "host": "127.0.0.1", "port": os.environ.get("PGPORT", "5432"),
                    "dbname": "footscore_restore_ci", "user": RUNTIME_ROLE,
                    "password": password, "connect_timeout": 5,
                }
                # Authenticate as a truly distinct LOGIN, not SET ROLE under
                # the privileged migration-owner connection.
                with psycopg.connect(**runtime_params) as runtime:
                    report = audit_runtime_connection(runtime, "footscore")
                    assert report["runtime_role_policy_passed"]
                    assert report["table_count"] > 15
                    assert report["sequence_count"] > 15
                    assert not report["role_names_or_credentials_exported"]
                    with runtime.cursor() as app:
                        app.execute("SELECT current_user, session_user")
                        assert app.fetchone() == (RUNTIME_ROLE, RUNTIME_ROLE)
                        app.execute(
                            "SELECT has_schema_privilege(current_user, 'public', 'CREATE')"
                        )
                        assert app.fetchone()[0] is False
                        app.execute("SELECT COUNT(*) FROM public.matches")
                        assert app.fetchone()[0] >= 181
                        app.execute("SELECT COUNT(*) FROM public.live_updates")
                        assert app.fetchone()[0] >= 1441

                        app.execute(
                            "INSERT INTO public.matches "
                            "(provider, provider_id, status, observed_at, updated_at) "
                            "VALUES ('ci-synthetic', 'ci-runtime-only', 'FT', "
                            "CURRENT_TIMESTAMP, CURRENT_TIMESTAMP) RETURNING id"
                        )
                        match_id = app.fetchone()[0]
                        app.execute(
                            "INSERT INTO public.live_updates "
                            "(match_id, kind, payload, created_at) "
                            "VALUES (%s, 'ci_runtime_only', '{}', CURRENT_TIMESTAMP) "
                            "RETURNING id",
                            (match_id,),
                        )
                        update_id = app.fetchone()[0]
                        assert match_id > 181 and update_id > 1441
                        app.execute(
                            "UPDATE public.matches SET status='LIVE' WHERE id=%s "
                            "RETURNING status", (match_id,),
                        )
                        assert app.fetchone()[0] == "LIVE"
                        app.execute(
                            "DELETE FROM public.live_updates WHERE id=%s RETURNING id",
                            (update_id,),
                        )
                        assert app.fetchone()[0] == update_id
                        app.execute(
                            "DELETE FROM public.matches WHERE id=%s RETURNING id",
                            (match_id,),
                        )
                        assert app.fetchone()[0] == match_id
                        app.execute(
                            f"INSERT INTO {FUTURE_TABLE} (note) "
                            "VALUES ('synthetic-future-table') RETURNING id"
                        )
                        assert app.fetchone()[0] > 0
                        app.execute(f"SELECT COUNT(*) FROM {FUTURE_TABLE}")
                        assert app.fetchone()[0] == 1

                        for forbidden in (
                            "CREATE TABLE public.ci_runtime_bad (id integer)",
                            "ALTER TABLE public.matches ADD COLUMN ci_bad integer",
                            "DROP TABLE public.matches",
                            "TRUNCATE TABLE public.matches",
                        ):
                            _assert_denied(app, forbidden)

                        # PostgreSQL can emit only a WARNING (no exception)
                        # for GRANT without grant option. Assert the EFFECT,
                        # rather than treating a warning as a security breach.
                        app.execute("SAVEPOINT ci_permission_grant_probe")
                        try:
                            app.execute("GRANT INSERT ON public.matches TO PUBLIC")
                        except psycopg.errors.InsufficientPrivilege:
                            app.execute("ROLLBACK TO SAVEPOINT ci_permission_grant_probe")
                        else:
                            app.execute(
                                "SELECT has_table_privilege('PUBLIC', "
                                "'public.matches', 'INSERT')"
                            )
                            unexpectedly_granted = app.fetchone()[0]
                            app.execute("ROLLBACK TO SAVEPOINT ci_permission_grant_probe")
                            assert not unexpectedly_granted, (
                                "Runtime was able to grant INSERT to PUBLIC"
                            )
                    runtime.rollback()
            finally:
                # The distinct runtime connection is closed before cleaning
                # up its grants and cluster-global temporary role.
                owner.execute(f"DROP TABLE IF EXISTS {FUTURE_TABLE}")
                owner.execute(
                    sql.SQL("DROP OWNED BY {}").format(role)
                )
                owner.execute(
                    sql.SQL("DROP ROLE {}").format(role)
                )
    print(
        "Distinct CI LOGIN runtime can read/write matches and future tables, "
        "passes role audit but cannot modify schema, drop tables or grant permissions; "
        "temporary role and objects cleaned."
    )


if __name__ == "__main__":
    run()
